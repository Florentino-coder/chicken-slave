const DICTS: Record<Lang, Record<MessageKey, string>> = { th, en };

export function setLang(lang: Lang) {
  prefs.set('lang', lang);
  document.documentElement.lang = lang;
  setState({ lang });
}

export function translate(lang: Lang, key: MessageKey, vars?: Record<string, string | number>): string {
  const text = DICTS[lang][key] ?? th[key] ?? key;
  return vars ? text.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? `{${k}}`)) : text;
}

/** Translate outside React (toasts, socket handlers). */
export function t(key: MessageKey, vars?: Record<string, string | number>) {
  return translate(getState().lang, key, vars);
}

export function useT() {
  const lang = useStore((s) => s.lang);
  return useCallback((key: MessageKey, vars?: Record<string, string | number>) => translate(lang, key, vars), [lang]);
}

/** Error code from the server to a message; unknown codes fall back to the code itself. */
export function errorText(code: string) {
  const key = `err.${code}` as MessageKey;
  return key in th ? t(key) : code;
}
